"""Audit cavt_entries.csv against per-entry text (entry boundaries located as in cavt_shelfmarks.py).
Compares page-level flags (n_inedita_on_pages, edition_years) with entry-level evidence.
Usage: python3 scripts/cavt_audit.py 12000 > CAVT_AUDIT.md"""
import re, csv, difflib, sys
rows = {int(r['cavt_no']): r for r in csv.DictReader(open('raw/cavt/cavt_entries.csv'))}
gaps = {}; sec = None
for l in open('CAVT_GAPS.md'):
    if l.startswith('## '): sec = l[3:6]
    m = re.match(r'\| (\d+) \| ([^|]+)\|', l)
    if sec in ('3.1', '3.2', '3.3') and m: gaps[int(m.group(1))] = 'ABC'['123'.index(sec[2])]
L = open('raw/cavt/cavt.md').read().split('\n'); END = int(sys.argv[1])
def norm(x): return re.sub(r'^[\W\dIlOo]{0,6}[.,:]?\s*', '', x.strip()).lower()
C = [(i, norm(l)) for i, l in enumerate(L) if 1200 < i < END and 3 < len(l.strip()) < 120]
cands = {}
for n in range(1, 278):
    t = rows[n]['title'].lower(); tp = re.sub(r'\s*\(.*', '', t); cs = []
    for i, r in C:
        if difflib.SequenceMatcher(None, r[:len(t)+3], t).quick_ratio() < 0.6: continue
        s = max(difflib.SequenceMatcher(None, r[:len(t)+3], t).ratio(), difflib.SequenceMatcher(None, r[:len(tp)], tp).ratio()-0.05)
        if s > 0.7: cs.append((i, s))
    cands[n] = cs
states = [(1200, 0, None, 0)]
for n in range(1, 278):
    new = []
    for i, s in cands[n]:
        p = max((st for st in states if st[0] < i), key=lambda st: st[1], default=None)
        if p: new.append((i, p[1]+s, p, n))
    states += new
end = max(states, key=lambda st: st[1]); starts = {}
while end and end[3]: starts[end[3]] = end[0]; end = end[2]
ks = sorted(starts)
def text(k):
    j = ks.index(k); e = starts[ks[j+1]] if j+1 < len(ks) else END
    t = ' '.join(l for l in L[starts[k]:e] if not l.startswith('<!--'))
    return re.sub(r'-\s+(?=[a-z])', '', t)
INED = re.compile(r'[IlL1|]n[eé]d[il1]t(?:ae|a|um|i|us|o)\b|non(dum)? edit|unpublished|inédit', re.I)
ED = re.compile(r'\b(Ed\.|Editio\b|Editiones\b|edidit|ediderunt)', re.I)
YR = re.compile(r'\b(1[5-9]\d\d)\b')
COD = re.compile(r'\bCodd?\.?\s*:')
out = {'unloc': [], 'ined_miss': [], 'ined_false': [], 'yrs_extra': [], 'yrs_miss': [], 'paratur': []}
for n in range(1, 278):
    r = rows[n]
    if n not in starts: out['unloc'].append(n); continue
    t = text(n); ined = bool(INED.search(t)); page_ined = int(r['n_inedita_on_pages']) > 0
    yrs = set(YR.findall(t)); csv_y = set(r['edition_years'].split())
    if ined and not page_ined: out['ined_miss'].append(n)
    if page_ined and not ined: out['ined_false'].append(n)
    if re.search(r'paratur', t, re.I): out['paratur'].append(n)
    ex = sorted(csv_y - yrs); ms = sorted(yrs - csv_y) if ED.search(t) else []
    if ex: out['yrs_extra'].append((n, ex))
    if ms and not csv_y: out['yrs_miss'].append((n, ms[:8]))
def T(n): return f"{n} {rows[n]['title'][:60]}" + (f" [gap {gaps[n]}]" if n in gaps else "")
p = print
p("# CAVT data audit\n\nGenerated by `scripts/cavt_audit.py`. Entry text is located with the same title-matching DP as `cavt_shelfmarks.py`; heuristics, verify against the PDF.\n")
p(f"Located {len(starts)}/277 entries. Unlocated: {out['unloc']}\n")
p(f"## 1. Inedita in the entry text but n_inedita_on_pages = 0 (reverse error) — {len(out['ined_miss'])}")
for n in out['ined_miss']: p(f"- {T(n)}")
p(f"\n## 2. Page flagged Inedita but entry text has none (neighbour leak) — {len(out['ined_false'])}")
for n in out['ined_false']: p(f"- {T(n)}")
p(f"\n## 3. 'Editio paratur' entries (check for post-1998 editions) — {len(out['paratur'])}")
for n in out['paratur']: p(f"- {T(n)}")
p(f"\n## 4. edition_years empty but entry has an edition section with years — {len(out['yrs_miss'])}")
for n, y in out['yrs_miss']: p(f"- {T(n)}: {' '.join(y)}")
p(f"\n## 5. edition_years contains years absent from the entry text (neighbour leak) — {len(out['yrs_extra'])}")
for n, y in out['yrs_extra']: p(f"- {T(n)}: {' '.join(y)}")
